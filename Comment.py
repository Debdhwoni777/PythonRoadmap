# ============================================================
#                    PYTHON COMMENTS
# ============================================================

# A comment is a line of text that Python does NOT execute.
# Comments are used to explain what the code does.

print("India is my country")


# ------------------------------------------------------------
# 1. SINGLE-LINE COMMENT
# ------------------------------------------------------------

# This is a single-line comment.

print("Hello, Python!")  # This is an inline comment


# ------------------------------------------------------------
# 2. MULTI-LINE COMMENTS
# ------------------------------------------------------------

# Python does not have a special multi-line comment syntax.
# We can use # on each line:

# This is line 1
# This is line 2
# This is line 3

print("I am learning Python")


# ------------------------------------------------------------
# 3. TRIPLE-QUOTED STRINGS
# ------------------------------------------------------------

"""
This is a multi-line string.

It is NOT technically a comment.
Python treats it as a string.
"""

print("Keep learning! 🚀")


# ============================================================
# NOTE:
# Use # for comments.
# Use """ """ for multi-line strings/docstrings.
# ============================================================