# ============================================================
#                  PYTHON ESCAPE SEQUENCES
# ============================================================

# Escape sequences are special characters written using
# a backslash (\) inside a string.

# ------------------------------------------------------------
# 1. NEW LINE — \n
# ------------------------------------------------------------

print("Hello\nPython")

# Output:
# Hello
# Python


# ------------------------------------------------------------
# 2. TAB — \t
# ------------------------------------------------------------

print("Name:\tDhwoni")
print("Age:\t16")

# Output:
# Name:   Dhwoni
# Age:    16


# ------------------------------------------------------------
# 3. BACKSLASH — \\
# ------------------------------------------------------------

print("C:\\Users\\Dhwoni\\Desktop")

# Output:
# C:\Users\Dhwoni\Desktop


# ------------------------------------------------------------
# 4. DOUBLE QUOTE — \"
# ------------------------------------------------------------

print("He said, \"Python is easy!\"")

# Output:
# He said, "Python is easy!"


# ------------------------------------------------------------
# 5. SINGLE QUOTE — \'
# ------------------------------------------------------------

print('It\'s a beautiful day.')

# Output:
# It's a beautiful day.


# ------------------------------------------------------------
# 6. BACKSPACE — \b
# ------------------------------------------------------------

print("Helloo\b")

# \b moves the cursor one position backward.


# ------------------------------------------------------------
# 7. CARRIAGE RETURN — \r
# ------------------------------------------------------------

print("Python\rHello")

# \r moves the cursor to the beginning of the line.


# ------------------------------------------------------------
# 8. BELL — \a
# ------------------------------------------------------------

print("\a")

# May produce a system alert sound,
# depending on your computer/terminal.


# ============================================================
#                 IMPORTANT ESCAPE SEQUENCES
# ============================================================

# \n  → New line
# \t  → Tab
# \\  → Backslash
# \"  → Double quote
# \'  → Single quote
# \b  → Backspace
# \r  → Carriage return
# \a  → Bell/alert


